package com.companyportal.backend.tools;

import io.zonky.test.db.postgres.embedded.EmbeddedPostgres;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import javax.sql.DataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * DbBackupTool on a real PostgreSQL: a backup of one schema restored into a schema of an empty database gives the same
 * tables and rows; the portal's own tables, also when they move from public to portal.
 */
class DbBackupToolTest {

    private static final String PORTAL = FlywayMigrationTest.SCHEMA;

    private static EmbeddedPostgres pg;

    @TempDir
    Path backups;

    @BeforeAll
    static void start() throws Exception {
        pg = EmbeddedPostgres.builder().start();
    }

    @AfterAll
    static void stop() throws Exception {
        if (pg != null) pg.close();
    }

    @Test
    void dataComesBackExactlyWithItsKeysCountersAndRlsInAnotherSchema() throws Exception {
        DataSource from = database("bk_from", "app_a");
        JdbcTemplate src = new JdbcTemplate(from);
        src.execute("""
                create schema app_a; set search_path to app_a;
                create table brands (id bigint generated by default as identity primary key, code varchar(10) not null unique,
                    rate numeric(5,2) check (rate >= 0));
                create table people (id bigint generated by default as identity primary key, name text not null,
                    brand_id bigint references brands, boss_id bigint references people, photo bytea, joined date,
                    status varchar(20) not null default 'NEW' check (status in ('NEW','DONE')), at timestamptz);
                create index ix_people_name on people (lower(name));
                create sequence doc_numbers;
                create table docs (no bigint not null default nextval('doc_numbers') primary key, note text);
                alter table people enable row level security;""");
        src.update("insert into brands (code, rate) values ('DW', 12.50), ('AB', 0)");
        src.update("insert into people (name, brand_id, boss_id, photo, joined, at) values ('Boss', 1, null, ?, '2026-01-05', now())",
                (Object) new byte[]{0, 1, 2, (byte) 255, 10, 13, 92});
        src.update("insert into people (name, brand_id, boss_id, status) values ('Asha \"Q\" Menon', 2, 1, 'DONE')");
        src.update("insert into people (name, brand_id, boss_id) values (E'Tab\\there, new\\nline', 1, 2)");
        src.update("insert into docs (note) values ('first'), (null), ('third')");

        Path dir;
        try (Connection c = from.getConnection()) {
            dir = DbBackupTool.backupTo(c, "app_a", backups, "test");
        }
        assertThat(Files.readString(dir.resolve("manifest.tsv")).lines().filter(l -> !l.startsWith("#")).map(l -> l.split("\t")[0]))
                .containsExactly("brands", "docs", "people");
        assertThat(Files.readString(dir.resolve("schema.sql"))).doesNotContain("app_a");

        DataSource to = database("bk_to", PORTAL);
        try (Connection c = to.getConnection()) {
            DbBackupTool.restoreFrom(c, PORTAL, dir, DbBackupTool.Mode.EXACT);
        }
        JdbcTemplate dst = new JdbcTemplate(to);
        for (String q : List.of("select id, code, rate from %s.brands order by id",
                "select id, name, brand_id, boss_id, encode(photo, 'hex'), joined, status, at from %s.people order by id",
                "select no, note from %s.docs order by no")) {
            assertThat(dst.queryForList(q.formatted(PORTAL))).isEqualTo(src.queryForList(q.formatted("app_a")));
        }
        // the ID counters go on from where they were, the keys and checks hold, RLS is on, all in the new schema
        assertThat(dst.queryForObject("insert into brands (code) values ('NEW') returning id", Long.class)).isEqualTo(3L);
        assertThat(dst.queryForObject("insert into docs (note) values ('x') returning no", Long.class)).isEqualTo(4L);
        assertThatThrownBy(() -> dst.update("insert into people (name, brand_id) values ('x', 77)")).hasMessageContaining("foreign key");
        assertThatThrownBy(() -> dst.update("insert into people (name, status) values ('x', 'MAYBE')")).hasMessageContaining("check");
        assertThatThrownBy(() -> dst.update("insert into brands (code) values ('DW')")).hasMessageContaining("unique");
        assertThat(dst.queryForObject("select c.relrowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace"
                + " where n.nspname = 'portal' and c.relname = 'people'", Boolean.class)).isTrue();
        assertThat(dst.queryForObject("select count(*) from pg_indexes where schemaname = 'portal' and indexname = 'ix_people_name'", Integer.class)).isEqualTo(1);
        assertThat(dst.queryForObject("select count(*) from pg_tables where schemaname = 'public'", Integer.class)).isZero();

        // never over existing tables
        try (Connection c = to.getConnection()) {
            assertThatThrownBy(() -> DbBackupTool.restoreFrom(c, PORTAL, dir, DbBackupTool.Mode.EXACT)).hasMessageContaining("already has tables");
        }
    }

    @Test
    void thePortalMovesFromPublicIntoAFreshFlywaySchema() throws Exception {
        // the live database today: the portal's tables in public, with the old Flyway history (V1 baseline .. V4), a
        // column the new schema added since (sales_enquiries.visitor_notified) and one it no longer has
        DataSource from = database("bk_public", "public");
        FlywayMigrationTest.flyway(from, "public").migrate();
        JdbcTemplate src = new JdbcTemplate(from);
        src.execute("""
                alter table sales_enquiries drop column visitor_notified;
                alter table brands add column old_fax varchar(20);
                delete from flyway_schema_history;
                insert into flyway_schema_history (installed_rank, version, description, type, script, checksum, installed_by, execution_time, success)
                values (1, '1', '<< Flyway Baseline >>', 'BASELINE', '<< Flyway Baseline >>', null, 'postgres', 0, true),
                       (2, '2', 'legacy schema fixes', 'SQL', 'V2__legacy_schema_fixes.sql', 1, 'postgres', 5, true),
                       (3, '3', 'sales enquiries', 'SQL', 'V3__sales_enquiries.sql', 2, 'postgres', 5, true),
                       (4, '4', 'sales enquiry follow up', 'SQL', 'V4__sales_enquiry_follow_up.sql', 3, 'postgres', 5, true)""");
        src.update("insert into brands (code, name, active, old_fax) values ('DW', 'Acme', true, '0484-200'), ('AB', 'Beta', true, null)");
        src.update("insert into office_holidays (holiday_date, name, brand_id) values ('2026-12-25', 'Christmas', 1)");
        src.update("""
                insert into sales_enquiries (kind, name, phone, email, notified, created_at, status)
                values ('DEMO', 'Asha', '9847012345', 'a@example.com', true, now(), 'NEW')""");

        Path dir;
        try (Connection c = from.getConnection()) {
            dir = DbBackupTool.backupTo(c, "public", backups, "test");
        }

        // the new project: Flyway makes portal from the one V1, then the data goes in
        DataSource to = database("bk_portal", PORTAL);
        DbBackupTool.migrate(to, PORTAL);
        try (Connection c = to.getConnection()) {
            DbBackupTool.restoreFrom(c, PORTAL, dir, DbBackupTool.Mode.DATA_ONLY);
        }
        JdbcTemplate dst = new JdbcTemplate(to);
        // the backend starting there: nothing to migrate, the check passes, its own history only
        assertThat(FlywayMigrationTest.flyway(to, PORTAL).migrate().migrationsExecuted).isZero();
        FlywayMigrationTest.validateUrl(pg.getJdbcUrl("postgres", "bk_portal"), PORTAL);
        // its own history: the app's scripts, none of the old database's
        assertThat(dst.queryForList("select script from portal.flyway_schema_history where version is not null order by installed_rank", String.class))
                .startsWith("V1__portal_schema.sql").doesNotContain("V2__legacy_schema_fixes.sql", "V3__sales_enquiries.sql", "V4__sales_enquiry_follow_up.sql");
        // the data, with the new column at its default and the dropped one left out
        assertThat(dst.queryForList("select code, name from portal.brands order by id")).hasSize(2);
        assertThat(dst.queryForObject("select visitor_notified from portal.sales_enquiries", Boolean.class)).isFalse();
        // ID counters go on after the data; the foreign keys are back
        assertThat(dst.queryForObject("insert into portal.brands (code, name, active) values ('NW', 'New', true) returning id", Long.class)).isEqualTo(3L);
        assertThatThrownBy(() -> dst.update("insert into portal.employees (name, user_id, role, brand_id, active, must_change_password, failed_attempts, password_hash, emp_number)"
                + " values ('x', 'x', 'EMPLOYEE', 999, true, false, 0, 'x', 'X1')")).hasMessageContaining("foreign key");
        assertThat(dst.queryForObject("select count(*) from pg_tables where schemaname = 'public'", Integer.class)).isZero();
    }

    @Test
    void dataThatBreaksAForeignKeyIsRefusedAndNothingIsKept() throws Exception {
        DataSource from = database("bk_broken", "public");
        FlywayMigrationTest.flyway(from, "public").migrate();
        JdbcTemplate src = new JdbcTemplate(from);
        src.update("insert into brands (code, name, active) values ('DW', 'Acme', true)");
        src.update("insert into office_holidays (holiday_date, name, brand_id) values ('2026-12-25', 'Christmas', 1)");
        src.execute("alter table office_holidays drop constraint " + src.queryForObject(
                "select conname from pg_constraint where conrelid = 'public.office_holidays'::regclass and contype = 'f'", String.class));
        src.update("update office_holidays set brand_id = 77");
        Path dir;
        try (Connection c = from.getConnection()) {
            dir = DbBackupTool.backupTo(c, "public", backups, "test");
        }
        DataSource to = database("bk_broken_to", PORTAL);
        DbBackupTool.migrate(to, PORTAL);
        try (Connection c = to.getConnection()) {
            assertThatThrownBy(() -> DbBackupTool.restoreFrom(c, PORTAL, dir, DbBackupTool.Mode.DATA_ONLY)).hasMessageContaining("foreign key");
        }
        assertThat(new JdbcTemplate(to).queryForObject("select count(*) from portal.brands", Integer.class)).isZero();
    }

    /**
     * Proves a real backup restores the way the move does it: Flyway makes the portal schema in a throw-away local
     * PostgreSQL, the backup's data goes in (every row count and foreign key checked), then the app's start-up check.
     * {@code ./mvnw test -Dtest=DbBackupToolTest#aRealBackupRestores -Ddb.verify=<backup folder>}
     */
    @Test
    @EnabledIfSystemProperty(named = "db.verify", matches = ".+")
    void aRealBackupRestores() throws Exception {
        DataSource to = database("bk_verify", PORTAL);
        DbBackupTool.migrate(to, PORTAL);
        try (Connection c = to.getConnection()) {
            DbBackupTool.restoreFrom(c, PORTAL, Path.of(System.getProperty("db.verify")), DbBackupTool.Mode.DATA_ONLY);
        }
        assertThat(FlywayMigrationTest.flyway(to, PORTAL).migrate().migrationsExecuted).isZero();
        FlywayMigrationTest.validateUrl(pg.getJdbcUrl("postgres", "bk_verify"), PORTAL);
        System.out.println("The backup restores into a Flyway-made " + PORTAL + " schema, and passes the app's start-up check");
    }

    /** A new database whose connections work in this schema. */
    private static DataSource database(String name, String schema) {
        new JdbcTemplate(pg.getPostgresDatabase()).execute("create database " + name);
        return new DriverManagerDataSource(pg.getJdbcUrl("postgres", name) + "&currentSchema=" + schema);
    }
}

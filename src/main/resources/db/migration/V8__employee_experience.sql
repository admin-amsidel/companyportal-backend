-- Work experience a person lists on their own profile: earlier jobs (company, role, months from and to, what they did).

create table employee_experiences (
    id bigint generated by default as identity,
    employee_id bigint not null,
    company_name varchar(150) not null,
    job_title varchar(100) not null,
    employment_type varchar(12) not null check ((employment_type in ('FULL_TIME','PART_TIME','CONTRACT','INTERNSHIP','FREELANCE'))),
    location varchar(150),
    start_month date not null,
    end_month date,
    responsibilities varchar(2000),
    achievements varchar(1000),
    tools varchar(300),
    reason_for_leaving varchar(300),
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    primary key (id)
);
alter table employee_experiences add constraint fk_employee_experience_employee foreign key (employee_id) references employees;
create index ix_employee_experience_employee on employee_experiences (employee_id);

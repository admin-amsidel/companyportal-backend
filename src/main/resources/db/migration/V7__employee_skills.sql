-- Skills a person lists on their own profile (Java, Spring Boot, AutoCAD...), each with an optional note. Not the skills
-- rated in a performance review (review_skills).

create table employee_skills (
    id bigint generated by default as identity,
    employee_id bigint not null,
    name varchar(60) not null,
    note varchar(500),
    sort_order integer not null,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_employee_skill_name unique (employee_id, name)
);
alter table employee_skills add constraint fk_employee_skill_employee foreign key (employee_id) references employees;
create index ix_employee_skill_employee on employee_skills (employee_id);

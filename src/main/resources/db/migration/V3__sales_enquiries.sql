-- Call-back and demo requests left in the website's support chat (entity SalesEnquiry).

create table sales_enquiries (
    id bigint generated by default as identity,
    company varchar(120),
    created_at timestamp(6) with time zone not null,
    demo_date date,
    demo_time time(0),
    email varchar(120) not null,
    kind varchar(20) not null check ((kind in ('CALLBACK','DEMO'))),
    message varchar(500),
    name varchar(80) not null,
    notified boolean not null,
    phone varchar(20) not null,
    primary key (id)
);

create index ix_sales_enquiry_created on sales_enquiries (created_at);

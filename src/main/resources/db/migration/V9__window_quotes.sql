-- Door & window quotes (Product portal > Sales): quotations made in the door and window configurator. The items
-- (each design with its priced bill of materials) are kept as a JSON snapshot, so later rate changes never alter an old quote.

create table window_quotes (
    id bigint generated by default as identity,
    number varchar(40) not null,
    brand_id bigint not null,
    created_by_id bigint,
    quote_date date not null,
    valid_until date not null,
    status varchar(10) not null check ((status in ('DRAFT','SENT','ACCEPTED','REJECTED'))),
    customer_name varchar(150) not null,
    customer_phone varchar(30),
    customer_email varchar(150),
    site_address varchar(500),
    notes varchar(2000),
    subtotal numeric(14,2) not null,
    discount_pct numeric(5,2) not null,
    discount numeric(14,2) not null,
    tax_pct numeric(5,2) not null,
    tax numeric(14,2) not null,
    grand_total numeric(14,2) not null,
    currency varchar(3) not null,
    item_count integer not null,
    items_json text not null,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    primary key (id)
);
alter table window_quotes add constraint uk_window_quote_number unique (number);
alter table window_quotes add constraint fk_window_quote_brand foreign key (brand_id) references brands;
alter table window_quotes add constraint fk_window_quote_created_by foreign key (created_by_id) references employees;
create index ix_window_quote_brand on window_quotes (brand_id);

-- Payroll, reworked:
--  * an exit (last working) date on the employee: pay stops after it, the last month is paid up to it;
--  * salary revisions: a person may have several salaries in a financial year, each from its own date (a raise in
--    October), instead of one per year;
--  * the year's income tax set-up (regime, old-regime declaration, and income and tax already paid this year outside
--    the portal) moves to its own table, one row per person and year, shared by the year's revisions;
--  * EPF, ESI and professional tax are worked out by payroll when they apply to a salary;
--  * loss-of-pay days may be half days, and the unpaid leave counted into them is kept on the payslip;
--  * professional tax slabs (per half year), editable by payroll.

alter table employees add column exit_date date;

-- salary revisions
alter table salary_structures drop constraint if exists uk_salary_employee_year;
alter table salary_structures add constraint uk_salary_employee_from unique (employee_id, effective_from);
alter table salary_structures add column pf_applies boolean default false not null;
alter table salary_structures add column pf_full_wage boolean default false not null;
alter table salary_structures add column esi_applies boolean default false not null;
alter table salary_structures add column pt_applies boolean default false not null;
-- salaries that had an EPF or professional tax amount keep it, now worked out
update salary_structures s set pf_applies = true where exists (select 1 from salary_lines l join pay_components c on c.id = l.component_id
    where l.structure_id = s.id and upper(c.code) = 'EPF' and l.monthly_amount > 0);
update salary_structures s set pt_applies = true where exists (select 1 from salary_lines l join pay_components c on c.id = l.component_id
    where l.structure_id = s.id and upper(c.code) = 'PT' and l.monthly_amount > 0);

-- the year's income tax set-up
create table payroll_tax_years (
    id bigint generated by default as identity,
    employee_id bigint not null,
    fy_start_year integer not null,
    tax_regime varchar(10) not null check ((tax_regime in ('NEW','OLD','MANUAL'))),
    tax_declared numeric(14,2),
    outside_income numeric(14,2),
    outside_tax numeric(14,2),
    updated_by bigint,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_tax_year_employee unique (employee_id, fy_start_year)
);
alter table payroll_tax_years add constraint fk_tax_year_employee foreign key (employee_id) references employees;
alter table payroll_tax_years add constraint fk_tax_year_updated_by foreign key (updated_by) references employees;
insert into payroll_tax_years (employee_id, fy_start_year, tax_regime, tax_declared, updated_by, created_at, updated_at)
    select employee_id, fy_start_year, coalesce(tax_regime, 'MANUAL'), tax_declared, updated_by, created_at, updated_at
    from salary_structures;
alter table salary_structures drop column tax_regime;
alter table salary_structures drop column tax_declared;

-- payslips: half days of loss of pay, and the unpaid leave counted
alter table payslips alter column lop_days type numeric(4,1);
alter table payslips alter column paid_days type numeric(4,1);
alter table payslips add column unpaid_leave_days numeric(4,1);

-- professional tax slabs: the tax for a half year (April-September, October-March) on that half year's gross pay
create table professional_tax_slabs (
    id bigint generated by default as identity,
    from_income numeric(14,2) not null,
    half_year_tax numeric(10,2) not null,
    primary key (id),
    constraint uk_pt_slab_from unique (from_income)
);
-- the slabs themselves are added at start-up when there are none (PayrollBootstrap: Kerala's), so a restored backup
-- finds the table empty
